const isHan = (character) => /[\\u3400-\\u9FFF\\uF900-\\uFAFF々〆ヶ]/u.test(character);

export function annotateKanjiFurigana(value = "") {
  const text = String(value);
  let output = "";
  for (let index = 0; index < text.length;) {
    const character = String.fromCodePoint(text.codePointAt(index));
    if (!isHan(character)) {
      output += character;
      index += character.length;
      continue;
    }

    let node = trie;
    let cursor = index;
    let best = null;
    while (cursor < text.length) {
      const next = String.fromCodePoint(text.codePointAt(cursor));
      node = node[next];
      if (!node) break;
      cursor += next.length;
      if (node.$reading) best = { end: cursor, reading: node.$reading };
    }

    if (!best) {
      output += character;
      index += character.length;
      continue;
    }

    const word = text.slice(index, best.end);
    output += word;
    index = best.end;
    const existing = text.slice(index).match(/^[（(][ぁ-ゖァ-ヶー]+[）)]/u);
    if (existing) {
      output += existing[0];
      index += existing[0].length;
    } else {
      output += `（${best.reading}）`;
    }
  }
  return output;
}
