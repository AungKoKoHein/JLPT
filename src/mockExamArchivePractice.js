export const archivePracticeSets = sets.map((set) => {
  const questions = [];
  const add = (section, type, rows) => rows.forEach((row, index) => {
    if (section === "Reading") {
      const [passage, prompt, choices, answer, explanation] = row;
      questions.push({ id: `${set.id}-${section}-${index + 1}`, section, type, passage, prompt, choices, answer, explanation });
    } else {
      const [prompt, choices, answer, explanation] = row;
      questions.push({ id: `${set.id}-${section}-${index + 1}`, section, type, prompt, choices, answer, explanation });
    }
  });
  add("Vocabulary", "Word usage", set.vocabulary);
  add("Grammar", "Grammar in context", set.grammar);
  add("Reading", "Short passage", set.reading);
  return { id: set.id, title: set.title, sourceNote: set.sourceNote, questions };
});

export const shuffledQuestions = (questions) => {
  const shuffled = [...questions];
  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(Math.random() * (index + 1));
    [shuffled[index], shuffled[swapIndex]] = [shuffled[swapIndex], shuffled[index]];
  }
  return shuffled.slice(0, 60).map((question, index) => ({ ...question, id: `random-${index + 1}` }));
};
